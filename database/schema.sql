create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 120),
  slug extensions.citext not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  status text not null default 'active' check (status in ('active','suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.branches (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 120),
  code extensions.citext not null,
  phone text,
  address text,
  capacity integer not null default 0 check (capacity >= 0),
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, code),
  unique (id, organization_id)
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username extensions.citext not null unique check (username ~ '^[a-z0-9][a-z0-9._-]{2,31}$'),
  full_name text not null check (char_length(full_name) between 2 and 120),
  phone text,
  must_change_password boolean not null default true,
  account_status text not null default 'active' check (account_status in ('active','blocked')),
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.organization_users (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('owner','branch_manager','receptionist','member')),
  branch_id uuid,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id),
  foreign key (branch_id, organization_id)
    references public.branches(id, organization_id) on delete restrict,
  constraint staff_branch_required check (
    role in ('owner','member') or branch_id is not null
  )
);

create table public.members (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  home_branch_id uuid not null,
  auth_user_id uuid references public.profiles(id) on delete set null,
  member_number bigint generated by default as identity,
  full_name text not null check (char_length(full_name) between 2 and 120),
  phone text,
  national_id text,
  birth_date date,
  emergency_phone text,
  status text not null default 'active' check (status in ('active','inactive','blocked')),
  notes text,
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, member_number),
  unique (organization_id, national_id),
  unique (id, organization_id),
  foreign key (home_branch_id, organization_id)
    references public.branches(id, organization_id) on delete restrict
);

create table public.membership_plans (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  name text not null,
  duration_days integer not null check (duration_days > 0),
  session_limit integer check (session_limit is null or session_limit > 0),
  price_amount bigint not null check (price_amount >= 0),
  currency text not null default 'IRR' check (currency = 'IRR'),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, name),
  unique (id, organization_id)
);

create table public.memberships (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  branch_id uuid not null,
  member_id uuid not null,
  plan_id uuid not null,
  starts_on date not null,
  ends_on date not null,
  remaining_sessions integer check (remaining_sessions is null or remaining_sessions >= 0),
  status text not null default 'active' check (status in ('pending','active','expired','cancelled')),
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on >= starts_on),
  unique (id, organization_id),
  foreign key (branch_id, organization_id)
    references public.branches(id, organization_id) on delete restrict,
  foreign key (member_id, organization_id)
    references public.members(id, organization_id) on delete restrict,
  foreign key (plan_id, organization_id)
    references public.membership_plans(id, organization_id) on delete restrict
