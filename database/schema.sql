create table public.payment_records (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  branch_id uuid not null,
  member_id uuid,
  membership_id uuid,
  amount bigint not null check (amount > 0),
  currency text not null default 'IRR' check (currency = 'IRR'),
  method text not null check (method in ('cash','pos','bank_transfer')),
  status text not null default 'paid' check (status in ('paid','voided','refunded')),
  reference_number text,
  received_by uuid not null references public.profiles(id) on delete restrict,
  paid_at timestamptz not null default now(),
  voided_at timestamptz,
  voided_by uuid references public.profiles(id) on delete restrict,
  void_reason text,
  created_at timestamptz not null default now(),
  check ((status = 'voided') = (voided_at is not null)),
  foreign key (branch_id, organization_id)
    references public.branches(id, organization_id) on delete restrict,
  foreign key (member_id, organization_id)
    references public.members(id, organization_id) on delete restrict,
  foreign key (membership_id, organization_id)
    references public.memberships(id, organization_id) on delete restrict
);

